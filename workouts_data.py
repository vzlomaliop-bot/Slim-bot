def get_workout(day_index=None):
    """Возвращает тренировку по индексу или случайную."""
    if day_index is None:
        import random
        return random.choice(WORKOUTS)
    return WORKOUTS[day_index % len(WORKOUTS)]


def format_workout(w):
    lines = [
        f"**{w['name']}**",
        f"⏱ {w['duration']} | 🔥 {w['burn']}",
        f"📋 Формат: {w['format']}",
        "",
        "**Упражнения:**",
    ]
    for ex in w["exercises"]:
        lines.append(f"• {ex}")
    lines.append("")
    lines.append(f"💡 _{w['note']}_")
    return "\n".join(lines)
